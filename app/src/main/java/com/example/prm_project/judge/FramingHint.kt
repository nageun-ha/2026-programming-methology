package com.example.prm_project.judge

/**
 * 보정·운동 시작 전에 사용자에게 보여 줄 위치 안내. ③(#34, #35)이 문구로 표시한다.
 *
 * 좌우는 화면(거울) 기준이다. [com.example.prm_project.model.PoseFrame] 좌표가 이미 화면 기준이고,
 * 거울 미리보기에서는 화면 왼쪽 = 사용자 자신의 왼쪽이라 사용자가 느끼는 방향과도 같다.
 * 이동 안내는 잘린 쪽의 반대 방향이다. 화면 오른쪽이 잘리면 [MOVE_LEFT], 왼쪽이 잘리면 [MOVE_RIGHT]다.
 */
enum class FramingHint {
    /** 제대로 잡혔다. */
    OK,

    /** 미리보기 화면에서 왼쪽으로 이동. 화면 오른쪽 가장자리가 잘렸을 때다. */
    MOVE_LEFT,

    /** 미리보기 화면에서 오른쪽으로 이동. 화면 왼쪽 가장자리가 잘렸을 때다. */
    MOVE_RIGHT,

    /** 뒤로 물러남. 위·아래 가장자리가 잘렸거나 좌우 양쪽이 모두 잘렸을 때다. */
    STEP_BACK,

    /** 화면 대비 몸이 너무 작으니 가까이 옴. */
    COME_CLOSER,

    /** 관절이 하나도 잡히지 않음. */
    NOT_VISIBLE,

    /** 화면 안에 추정된 관절은 있지만 신뢰도가 전부 낮음. 조명이 어둡거나 가려졌을 때다. */
    LOW_LIGHT,
}
